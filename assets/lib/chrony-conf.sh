# shellcheck shell=bash
# shellcheck disable=SC2153,SC2154
# Generate /etc/chrony/chrony.conf and populate gpsd_sockets.
# Sourced by startup.sh; configuration globals are assigned there.

generate_chrony_conf() {
  gpsd_sockets=()

  {
    echo "# https://github.com/simonrupf/docker-chrony"
    echo
    echo "# chrony.conf file generated by startup script"
    echo "# located at $0"
    echo
    echo "# time servers provided by the NTP_SERVERS environment variable."
  } > "${CHRONY_CONF_FILE}"

  local server source_options
  local -a ntp_servers
  IFS=',' read -ra ntp_servers <<< "${NTP_SERVERS}"
  for server in "${ntp_servers[@]}"; do
    server="$(printf '%s' "${server}" | xargs)"
    [[ -n "${server}" ]] || continue

    if [[ ! "${server}" =~ ^[A-Za-z0-9._:-]+$ ]]; then
      echo "Invalid NTP server '${server}'" >&2
      exit 1
    fi

    if [[ "${server}" == 127.* ]]; then
      echo "server ${server}" >> "${CHRONY_CONF_FILE}"
      echo "local stratum 10" >> "${CHRONY_CONF_FILE}"
    else
      source_options=(iburst)
      if [[ "${NTP_SOURCE_TYPE}" == "pool" ]]; then
        source_options+=(maxsources 1)
      fi
      if [[ "${ENABLE_NTS}" == "true" ]]; then
        source_options+=(nts)
      fi
      echo "${NTP_SOURCE_TYPE} ${server} ${source_options[*]}" >> "${CHRONY_CONF_FILE}"
    fi
  done

  local -a pps_options

  # GPSD SOCK: each device basename gets its own chrony socket (gpsd timehint.c).
  # GPIO KPPS (/dev/ppsN) feeds /run/chrony.ppsN.sock; serial time feeds
  # /run/chrony.clk.<tty>.sock. Kernel PPS locks /dev/<pps> to that clk socket.
  if [[ "${ENABLE_GPSD_SOCK}" == "true" ]]; then
    echo "refclock SOCK /run/chrony.clk.${DEV_TTY}.sock offset ${NMEA_OFFSET} delay ${NMEA_DELAY} refid NMEA poll 0 noselect" >> "${CHRONY_CONF_FILE}"
    pps_options=(refid PPS precision 1e-7 poll 0)
    if [[ "${GPS_PREFER}" == "true" ]]; then
      pps_options+=(prefer)
    fi
    echo "refclock SOCK /run/chrony.${DEV_PPS}.sock ${pps_options[*]}" >> "${CHRONY_CONF_FILE}"
    gpsd_sockets+=("/run/chrony.clk.${DEV_TTY}.sock" "/run/chrony.${DEV_PPS}.sock")
  elif [[ "${ENABLE_KERNEL_PPS}" == "true" ]]; then
    echo "refclock SOCK /run/chrony.clk.${DEV_TTY}.sock offset ${NMEA_OFFSET} delay ${NMEA_DELAY} refid NMEA poll 0 noselect" >> "${CHRONY_CONF_FILE}"
    pps_options=(lock NMEA refid PPS precision 1e-7 poll 0)
    if [[ "${GPS_PREFER}" == "true" ]]; then
      pps_options+=(prefer)
    fi
    echo "refclock PPS /dev/${DEV_PPS} ${pps_options[*]}" >> "${CHRONY_CONF_FILE}"
    gpsd_sockets+=("/run/chrony.clk.${DEV_TTY}.sock")
  fi

  if [[ "${ENABLE_PTP}" == "true" ]]; then
    echo "refclock PHC /dev/${DEV_PTP} poll 3 dpoll -2 offset ${PTP_OFFSET} stratum 2" >> "${CHRONY_CONF_FILE}"
  fi

  {
    echo
    echo "driftfile /var/lib/chrony/chrony.drift"
    echo "makestep 0.1 3"
    if [[ -n "${NTP_DIRECTIVES:-}" ]]; then
      printf '%b\n' "${NTP_DIRECTIVES}"
    fi
    if [[ "${NOCLIENTLOG}" == "true" ]]; then
      echo "noclientlog"
    fi

    if [[ -n "${NTP_ALLOW}" ]]; then
      if [[ ! "${NTP_ALLOW}" =~ ^[A-Za-z0-9.:/-]+$ ]]; then
        echo "Invalid NTP_ALLOW network '${NTP_ALLOW}'" >&2
        exit 1
      fi
      echo
      echo "allow ${NTP_ALLOW}"
    fi
  } >> "${CHRONY_CONF_FILE}"
}
